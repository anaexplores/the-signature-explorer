#!/usr/bin/env node
// tools/build.mjs — the project's only build tool.
//
// Pass 1 (vendor): bundles sha256 (@noble/hashes) + secp256k1 + modular utilities
//   (@noble/curves) into ONE self-contained ESM file, js/vendor/noble.mjs.
// Pass 2 (screens): bundles js/screens/{intro,ecdsa,hash}.mjs (ESM, importing
//   js/schemes/* and js/vendor/noble.mjs) into classic/IIFE build/{intro,ecdsa,hash}.js —
//   exactly what the browser loads via <script src="build/...">, without "type=module".
//
// Modes:
//   node tools/build.mjs            — regular build + record sha256 in PROVENANCE/BUILD.md
//   node tools/build.mjs --check    — rebuild into a temp folder + compare sha256 (K9)
//   node tools/build.mjs --watch    — rebuild on changes under js/**
//
// Single source of truth: the build is the only place that touches node_modules/esbuild.
// Screens and schemes know nothing about the build.

import { build as esbuildBuild } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");

const VENDOR_OUT = path.join(ROOT, "js", "vendor", "noble.mjs");
const PROVENANCE_MD = path.join(ROOT, "js", "vendor", "noble.PROVENANCE.md");
const BUILD_MD = path.join(ROOT, "build", "BUILD.md");

const SCREENS = ["intro", "ecdsa", "hash"];
const GENERATED_BANNER =
  "/* GENERATED FILE — do not edit by hand. Source lives in js/**. Rebuild with `npm run build`. */";

const VENDOR_ENTRY_SOURCE = `
// Vendor entry (bundled by tools/build.mjs into js/vendor/noble.mjs).
// Reexports exactly what js/schemes/* need — nothing else — so the vendor bundle
// stays small and tree-shaken.
export { sha256 } from "@noble/hashes/sha256";
export { secp256k1 } from "@noble/curves/secp256k1";
export { mod, invert } from "@noble/curves/abstract/modular";
`;

function sha256File(filePath) {
  const buf = fs.readFileSync(filePath);
  return crypto.createHash("sha256").update(buf).digest("hex");
}

function readPkgVersions() {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
  return pkg.devDependencies;
}

/** Builds the vendor bundle into outfile (the regular path, or a temp one under --check). */
async function buildVendor(outfile) {
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  await esbuildBuild({
    stdin: {
      contents: VENDOR_ENTRY_SOURCE,
      resolveDir: ROOT,
      loader: "js",
    },
    outfile,
    bundle: true,
    minify: true,
    format: "esm",
    platform: "neutral",
    target: "es2020",
    banner: { js: GENERATED_BANNER },
    logLevel: "silent",
  });
}

/** Builds one classic/IIFE screen bundle into outfile. Requires vendorFile to already exist. */
async function buildScreen(name, outfile, vendorFile) {
  const entry = path.join(ROOT, "js", "screens", `${name}.mjs`);
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  await esbuildBuild({
    entryPoints: [entry],
    outfile,
    bundle: true,
    minify: true,
    format: "iife",
    platform: "browser",
    target: "es2020",
    banner: { js: GENERATED_BANNER },
    // vendorFile takes part in the import graph automatically (relative path
    // from js/screens/*.mjs to js/vendor/noble.mjs) — the parameter is here only to
    // make the call order (vendor before screens) explicit on the caller's side.
    logLevel: "silent",
  });
  void vendorFile;
}

async function buildAll(outDir) {
  const vendorOut = path.join(outDir, "js", "vendor", "noble.mjs");
  await buildVendor(vendorOut);
  const screenOuts = {};
  for (const name of SCREENS) {
    const outfile = path.join(outDir, "build", `${name}.js`);
    await buildScreen(name, outfile, vendorOut);
    screenOuts[name] = outfile;
  }
  return { vendorOut, screenOuts };
}

function writeProvenance({ vendorOut, screenOuts }) {
  const versions = readPkgVersions();
  const vendorHash = sha256File(vendorOut);
  fs.mkdirSync(path.dirname(PROVENANCE_MD), { recursive: true });
  fs.writeFileSync(
    PROVENANCE_MD,
    [
      "# noble.mjs — provenance",
      "",
      "Generated by `node tools/build.mjs` (esbuild one-shot vendor bundle).",
      "",
      "## Pinned versions (exact, from package.json devDependencies)",
      "",
      `- esbuild: ${versions.esbuild}`,
      `- @noble/hashes: ${versions["@noble/hashes"]}`,
      `- @noble/curves: ${versions["@noble/curves"]}`,
      "",
      "## Build command",
      "",
      "```",
      "node tools/build.mjs",
      "```",
      "",
      "## Artifact sha256",
      "",
      `- js/vendor/noble.mjs: \`${vendorHash}\``,
      "",
      "Verify reproducibility: `node tools/build.mjs --check` (exits non-zero on mismatch).",
      "",
    ].join("\n"),
  );

  fs.mkdirSync(path.dirname(BUILD_MD), { recursive: true });
  const lines = [
    "# build/ — provenance",
    "",
    "Generated by `node tools/build.mjs` (esbuild, classic/IIFE screen bundles).",
    "",
    "## Rebuild",
    "",
    "```",
    "node tools/build.mjs",
    "```",
    "",
    "## Artifact sha256",
    "",
  ];
  for (const name of SCREENS) {
    lines.push(`- build/${name}.js: \`${sha256File(screenOuts[name])}\``);
  }
  lines.push("", "Verify: `node tools/build.mjs --check` (exits non-zero on mismatch).", "");
  fs.writeFileSync(BUILD_MD, lines.join("\n"));
}

function readRecordedHashes() {
  const out = {};
  if (fs.existsSync(PROVENANCE_MD)) {
    const text = fs.readFileSync(PROVENANCE_MD, "utf8");
    const m = text.match(/js\/vendor\/noble\.mjs:\s*`([0-9a-f]{64})`/);
    if (m) out["js/vendor/noble.mjs"] = m[1];
  }
  if (fs.existsSync(BUILD_MD)) {
    const text = fs.readFileSync(BUILD_MD, "utf8");
    for (const name of SCREENS) {
      const re = new RegExp(`build/${name}\\.js:\\s*\`([0-9a-f]{64})\``);
      const m = text.match(re);
      if (m) out[`build/${name}.js`] = m[1];
    }
  }
  return out;
}

async function runBuild() {
  const result = await buildAll(ROOT);
  writeProvenance(result);
  console.log("✓ build: js/vendor/noble.mjs + build/{intro,ecdsa,hash}.js written, sha256 recorded.");
}

async function runCheck() {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "sigexp-build-check-"));
  try {
    const recorded = readRecordedHashes();
    const expectedKeys = ["js/vendor/noble.mjs", ...SCREENS.map((n) => `build/${n}.js`)];
    const missing = expectedKeys.filter((k) => !recorded[k]);
    if (missing.length) {
      console.error(
        `✗ build --check: no recorded sha256 for: ${missing.join(", ")}. Run \`node tools/build.mjs\` once to record provenance, commit the artifacts, then re-run --check.`,
      );
      process.exitCode = 1;
      return;
    }

    const { vendorOut, screenOuts } = await buildAll(tmpDir);
    let ok = true;

    const vendorFresh = sha256File(vendorOut);
    if (vendorFresh !== recorded["js/vendor/noble.mjs"]) {
      ok = false;
      console.error(
        `✗ js/vendor/noble.mjs is out of sync with sources.\n  recorded: ${recorded["js/vendor/noble.mjs"]}\n  fresh:    ${vendorFresh}`,
      );
    }

    for (const name of SCREENS) {
      const key = `build/${name}.js`;
      const fresh = sha256File(screenOuts[name]);
      if (fresh !== recorded[key]) {
        ok = false;
        console.error(`✗ ${key} is out of sync with sources.\n  recorded: ${recorded[key]}\n  fresh:    ${fresh}`);
      }
    }

    if (!ok) {
      console.error(
        "\n✗ build --check: FAIL — committed artifacts do not match a fresh rebuild. Run `node tools/build.mjs` and commit the result.",
      );
      process.exitCode = 1;
      return;
    }
    console.log("✓ build --check: PASS — committed artifacts match a fresh rebuild of js/**.");
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

async function runWatch() {
  console.log("👀 watch: rebuilding on changes under js/** …");
  let building = false;
  let pending = false;

  async function rebuild() {
    if (building) {
      pending = true;
      return;
    }
    building = true;
    try {
      await runBuild();
    } catch (err) {
      console.error("✗ build failed:", err.message);
    } finally {
      building = false;
      if (pending) {
        pending = false;
        rebuild();
      }
    }
  }

  await rebuild();

  const watchDir = path.join(ROOT, "js");
  let debounce = null;
  const trigger = () => {
    clearTimeout(debounce);
    debounce = setTimeout(rebuild, 100);
  };
  try {
    fs.watch(watchDir, { recursive: true }, trigger);
  } catch {
    // recursive watch unsupported on this platform (older Linux) — fall back to top-level dirs.
    for (const sub of fs.readdirSync(watchDir, { withFileTypes: true })) {
      if (sub.isDirectory()) fs.watch(path.join(watchDir, sub.name), trigger);
    }
  }
  console.log("watching js/** — Ctrl+C to stop.");
  // keep process alive
  await new Promise(() => {});
}

const args = process.argv.slice(2);
if (args.includes("--check")) {
  await runCheck();
} else if (args.includes("--watch")) {
  await runWatch();
} else {
  await runBuild();
}
